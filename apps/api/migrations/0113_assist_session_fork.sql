-- 会话分叉血缘：这条讨论是从哪一条分出来的（工作台 §28.1、HTTP §10.93、物理设计 §102）。
-- 2026-10-18，源码实现。仅追加一列，不改写任何既有迁移、不回填、不动消息/提案/附件/选择表。
--
-- 这一列表达的是**来源**，不是状态：分叉之后的两条会话各自独立生长，父会话不因为被
-- 分叉而变化（不推进修订、不改标题、不添子会话列表）。界面上「这条从哪来」只在需要
-- 解释那个「（1）」标题时读一次，因此它是可追溯的元数据，不是业务事实——
-- 会话归哪个项目、绑哪个目录、能不能发消息，全部仍由既有列与既有 Owner 决定。
--
-- 形状沿用 0006 的 `verification_sessions.parent_session_id`：同表自引用、可空、无 CHECK。
-- 与本表另一组可空列（pinned_at / unread_at / last_message_at）不同，那些是导航排序键，
-- 本列是一次写入后不再改写的**历史来源**；分叉命令是唯一写入方，父会话 ID 只在插入时写。
--
-- 为什么不在数据库里加 CHECK：`forked_from_session_id <> id` 看似必要，但子行 ID 由命令
-- 新生成，永远不可能等于父行 ID；父子同 Workspace 同样由应用 Owner 的行锁读取保证
-- （跨作用域的父会话按 RESOURCE_NOT_FOUND 拒掉，与既有会话命令同一口径）。
-- 为这两件不可能发生的事写约束属提前建设。

ALTER TABLE assist_sessions ADD COLUMN forked_from_session_id uuid
  REFERENCES assist_sessions (id);

-- 索引：不建。一张父会话可以有许多子会话（每分叉一次多一条），1:N 且查询只有两种——
-- 按子行 ID 直接读它自己的父 ID（主键命中，不需要索引），以及按父 ID 列出子会话
-- （本轮没有任何读方）。0006 给 verification_sessions 建的部分索引是因为那里要按父
-- 会话反查派生会话并强制「一个父只能派生一次」的 UNIQUE；本表既不反查也不唯一，
-- 照抄那枚索引只会多一个没人用的写放大。
--
-- 权限：0015 已对 assist_sessions 授表级 SELECT/INSERT/UPDATE，新列自动在既有授权范围内，
-- 因此不追加 GRANT（表级授权覆盖新列）。应用角色仍无 DELETE。
--
-- 兼容与回滚：纯追加一列，旧行取 NULL（不是任何会话的分叉），既有响应只多一个可空只读
-- 字段，旧客户端忽略它即可，Breaking Change: No。回退可直接保留该列（旧代码不读）；
-- 删除该列只丢失「这条从哪来」的来源说明，不丢失任何会话、消息、附件、回执或选择事实。
