import assert from 'node:assert/strict';
import {randomUUID} from 'node:crypto';
import test,{before,after} from 'node:test';
import fs from 'node:fs';
import {runMigrations} from '../../dist/src/infrastructure/migration-runner.js';
import {APP_DATABASE_URL,MIGRATION_DATABASE_URL,MIGRATIONS_DIRECTORY,openDatabase} from '../../dist/test/integration/integration-support.js';
import {createWorkspace,startTestApi,workspacePath} from '../../dist/test/integration/api-harness.js';
import {createAssistSession} from '../../dist/src/application/assist-commands.js';
import {createRepositories} from '../../dist/src/application/unit-of-work.js';
const app=openDatabase(APP_DATABASE_URL,'triage-chat-mode-zero-revision');
let api,wid;
before(async()=>{await runMigrations({connectionString:MIGRATION_DATABASE_URL,directory:MIGRATIONS_DIRECTORY});api=await startTestApi();wid=await createWorkspace(app.db);});
after(async()=>{await api?.stop();await app.close();});
test('the first chat mode switch must accept the actual initial revision zero',async()=>{
 const sid=(await createAssistSession(app.db,{workspaceId:wid,commandId:randomUUID(),projectId:null,title:'mode revision zero'})).result.session_id;
 const repos=createRepositories(app.db);
 const initial=await repos.assist.readSession(sid);assert.equal(String(initial.revision),'0');
 const route=workspacePath(wid,`/assist-sessions/${sid}/chat-mode`);
 const zero=await api.post(route,{command_id:randomUUID(),mode:'PLAN',expected_revision:'0'});
 const unchanged=await repos.assist.readSession(sid);assert.equal(unchanged.chat_mode,'CHAT');assert.equal(String(unchanged.revision),'0');
 const without=await api.post(route,{command_id:randomUUID(),mode:'PLAN'});
 assert.equal(without.status,200,without.text);assert.equal(without.body.result.revision,'1');
 const positive=await api.post(route,{command_id:randomUUID(),mode:'CHAT',expected_revision:'1'});
 assert.equal(positive.status,200,positive.text);assert.equal(positive.body.result.revision,'2');
 const stale=await api.post(route,{command_id:randomUUID(),mode:'GOAL',expected_revision:'1'});
 assert.equal(stale.status,409,stale.text);
 const evidence={initialRevision:String(initial.revision),zeroStatus:zero.status,zeroBody:zero.body,withoutRevisionStatus:without.status,positiveRevisionStatus:positive.status,staleRevisionStatus:stale.status};
 fs.writeFileSync('output/triage-defects-20261022/chat-mode-zero-revision.json',JSON.stringify(evidence,null,2));
 console.log('TRIAGE_CHAT_MODE_ZERO_REVISION',JSON.stringify(evidence));
 assert.equal(zero.status,200,'a newly created session must allow a mode transition guarded by its actual revision 0');
});
