import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test, { before, after } from 'node:test';
import fs from 'node:fs';
import { runMigrations } from '../../dist/src/infrastructure/migration-runner.js';
import { APP_DATABASE_URL, MIGRATION_DATABASE_URL, MIGRATIONS_DIRECTORY, openDatabase } from '../../dist/test/integration/integration-support.js';
import { createWorkspace, expectCommandAccepted, startTestApi, workspacePath } from '../../dist/test/integration/api-harness.js';
const app = openDatabase(APP_DATABASE_URL, 'triage-return-review-replay');
let api;
before(async () => { await runMigrations({ connectionString: MIGRATION_DATABASE_URL, directory: MIGRATIONS_DIRECTORY }); api = await startTestApi(); });
after(async () => { await api?.stop(); await app.close(); });
test('identical return-review command replays original receipt after project facts change', async () => {
  const wid = await createWorkspace(app.db);
  const post = (path, body) => api.post(workspacePath(wid, path), body);
  const createId = randomUUID();
  const project = expectCommandAccepted(await post('/projects', { command_id: createId, title: 'return review replay probe', project_type: 'GENERAL' }), 201, createId);
  const path = `/projects/${project.project_id}/return-reviews`;
  const commandId = randomUUID(); const body = { command_id: commandId };
  const firstResponse = await post(path, body);
  const first = expectCommandAccepted(firstResponse, 200, commandId);
  const unchangedResponse = await post(path, body);
  const unchanged = expectCommandAccepted(unchangedResponse, 200, commandId);
  assert.equal(unchanged.review_id, first.review_id);
  assert.equal(unchangedResponse.headers['command-replayed'], 'true');
  const taskCommandId = randomUUID();
  expectCommandAccepted(await post('/tasks', { command_id: taskCommandId, project_id: project.project_id, title: 'new fact after review', objective: 'new task', criteria: [] }), 201, taskCommandId);
  const replay = await post(path, body);
  const newCommandId = randomUUID();
  const freshResponse = await post(path, { command_id: newCommandId });
  const fresh = expectCommandAccepted(freshResponse, 200, newCommandId);
  assert.notEqual(fresh.review_id, first.review_id);
  const receipt = await api.get(workspacePath(wid, `/commands/${commandId}`));
  assert.equal(receipt.status, 200, receipt.text);
  fs.writeFileSync('D:/Develop/Relay-Agent/apps/api/output/triage-defects-20261022/return-review-replay-evidence.json', JSON.stringify({ first, unchanged, replayStatus: replay.status, replayBody: replay.body, fresh, receipt: receipt.body }, null, 2));
  console.log('TRIAGE_RETURN_REVIEW_REPLAY', JSON.stringify({ unchangedStatus: unchangedResponse.status, changedSameRequestStatus: replay.status, changedSameRequestCode: replay.body.code, originalReceiptExists: receipt.status === 200, freshCommandStatus: freshResponse.status, freshReviewDiffers: fresh.review_id !== first.review_id }));
  assert.equal(replay.status, 200, 'same HTTP body must replay the original command after unrelated project facts change');
  assert.equal(replay.body.result.review_id, first.review_id);
});
