import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import test, { before, after } from 'node:test';
import fs from 'node:fs';
import { runMigrations } from '../../dist/src/infrastructure/migration-runner.js';
import { APP_DATABASE_URL, MIGRATION_DATABASE_URL, MIGRATIONS_DIRECTORY, openDatabase } from '../../dist/test/integration/integration-support.js';
import { createWorkspace, expectCommandAccepted, startTestApi, workspacePath } from '../../dist/test/integration/api-harness.js';
const app = openDatabase(APP_DATABASE_URL, 'triage-memory-expiry-replay');
let api;
before(async () => { await runMigrations({ connectionString: MIGRATION_DATABASE_URL, directory: MIGRATIONS_DIRECTORY }); api = await startTestApi(); });
after(async () => { await api?.stop(); await app.close(); });
test('an expired memory does not invalidate the original successful create command replay', async () => {
  const wid = await createWorkspace(app.db);
  const path = workspacePath(wid, '/memories');
  const commandId = randomUUID();
  const body = { command_id: commandId, project_id: null, title: 'expiry replay', text: 'short-lived declared memory', confirmed: true, expires_at: new Date(Date.now() + 2000).toISOString() };
  const firstResponse = await api.post(path, body);
  const first = expectCommandAccepted(firstResponse, 201, commandId);
  const beforeExpiry = await api.post(path, body);
  assert.equal(beforeExpiry.status, 201, beforeExpiry.text);
  assert.equal(beforeExpiry.headers['command-replayed'], 'true');
  await new Promise(resolve => setTimeout(resolve, Math.max(0, Date.parse(body.expires_at) - Date.now()) + 200));
  const afterExpiry = await api.post(path, body);
  const receipt = await api.get(workspacePath(wid, `/commands/${commandId}`));
  assert.equal(receipt.status, 200, receipt.text);
  const memory = await api.get(workspacePath(wid, `/memories/${first.memory_id}`));
  assert.equal(memory.status, 200, memory.text);
  assert.equal(memory.body.effective_status, 'EXPIRED');
  const newPastRequest = await api.post(path, { ...body, command_id: randomUUID() });
  assert.equal(newPastRequest.status, 422, newPastRequest.text);
  const evidence = { first, beforeExpiryStatus: beforeExpiry.status, afterExpiryStatus: afterExpiry.status, afterExpiryBody: afterExpiry.body, originalReceipt: receipt.body, currentMemory: memory.body, newPastRequestStatus: newPastRequest.status };
  fs.writeFileSync('D:/Develop/Relay-Agent/apps/api/output/triage-defects-20261022/memory-expiry-replay-evidence.json', JSON.stringify(evidence, null, 2));
  console.log('TRIAGE_MEMORY_EXPIRY_REPLAY', JSON.stringify({ beforeExpiry: beforeExpiry.status, afterExpiry: afterExpiry.status, code: afterExpiry.body.code, receiptExists: receipt.status === 200, effectiveStatus: memory.body.effective_status, newPastRequest: newPastRequest.status }));
  assert.equal(afterExpiry.status, 201, 'replaying an already committed command must return its original result after expiry');
  assert.equal(afterExpiry.body.result.memory_id, first.memory_id);
});
