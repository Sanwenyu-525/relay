import { createElement } from "react";
import { afterEach, expect, it, vi } from "vitest";
import ContinuationPointPanel from "../../src/components/ContinuationPointPanel";
import { RelayApiError, type RelayApiClient } from "../../src/api/relayClient";
import { flush, mountReact } from "../../tests/mountApp";
let unmount: (() => void) | null = null;
afterEach(() => { unmount?.(); unmount = null; sessionStorage.clear(); });
it("接续点提交未到服务端且原回执持续404后，应能按冻结原身份重试而不是永久锁住", async () => {
  const capture = vi.fn(async (_input: { commandId: string; name: string; note: string | null }) => { throw new TypeError("network request failed before reaching server"); });
  const receipt = vi.fn(async () => { throw new RelayApiError({ status: 404, code: "COMMAND_NOT_FOUND", detail: "No committed command", retryable: false, retryAction: null, fieldErrors: [], expectedRevision: null, actualRevision: null }); });
  const client = { baseUrl: "http://probe.invalid", workspaceId: "workspace-probe", getContinuationPoints: vi.fn(async () => []), captureContinuationPoint: capture, getCommandReceipt: receipt } as unknown as RelayApiClient;
  let mounted = await mountReact(createElement(ContinuationPointPanel, { client, projectId: "project-probe" }));
  unmount = mounted.unmount;
  await mounted.wrapper.get('[data-testid="continuation-name"]').setValue("网络恢复后保存");
  await mounted.wrapper.get('[data-testid="continuation-note"]').setValue("必须保留这份原载荷");
  await mounted.wrapper.get('[data-testid="continuation-capture"]').trigger("click"); await flush();
  expect(capture).toHaveBeenCalledTimes(1); expect(receipt).toHaveBeenCalledTimes(1);
  const first = capture.mock.calls[0]![0];
  const query = mounted.wrapper.findAll("button").find(b => b.text() === "查询原命令回执")!;
  await query.trigger("click"); await flush();
  mounted.unmount(); unmount = null;
  mounted = await mountReact(createElement(ContinuationPointPanel, { client, projectId: "project-probe" })); unmount = mounted.unmount; await flush();
  const retry = mounted.wrapper.findAll("button").find(b => /重试|重新提交/.test(b.text()));
  const pending = JSON.parse(sessionStorage.getItem("relay:continuation-point:http://probe.invalid:workspace-probe:project-probe")!);
  const frozen = pending.id === first.commandId && pending.name === first.name && pending.note === first.note;
  console.log("TRIAGE_CONTINUATION_MISSING_RECEIPT", JSON.stringify({ writes: capture.mock.calls.length, receiptReads: receipt.mock.calls.length, pendingSurvivesRemount: frozen, captureDisabled: mounted.wrapper.get('[data-testid="continuation-capture"]').attributes("disabled") !== undefined, retryOffered: Boolean(retry), buttons: mounted.wrapper.findAll("button").map(b => b.text()) }));
  expect(frozen).toBe(true);
  expect(retry, "Only receipt queries remain after a never-committed command; no original-ID recovery action exists").toBeDefined();
});
