import { act, createElement } from "react";
import { MemoryRouter } from "react-router-dom";
import { afterEach, expect, it, vi } from "vitest";
import AssistView from "../../src/views/AssistView";
import { activateRelayConnection, resetRelayConnectionForTest } from "../../src/lib/relayConnection";
import { mountReact } from "../../tests/mountApp";
const wid = "11111111-1111-4111-8111-111111111111";
const pid = "22222222-2222-4222-8222-222222222222";
const sid = "33333333-3333-4333-8333-333333333333";
const mid = "44444444-4444-4444-8444-444444444444";
let unmount: (() => void) | null = null;
afterEach(() => { unmount?.(); unmount = null; vi.clearAllTimers(); vi.useRealTimers(); resetRelayConnectionForTest(); vi.unstubAllGlobals(); });
const json = (body: unknown, status = 200) => new Response(JSON.stringify(body), { status, headers: { "content-type": "application/json" } });
it("消息列表1.5秒轮询不能让3秒成功回包永久无法显示已完成回复", async () => {
  vi.useFakeTimers();
  let slow = false;
  let serverDone = false;
  let requests = 0;
  let completedReads = 0;
  const session = { id: sid, workspace_id: wid, project_id: pid, task_id: null, title: "slow messages probe", status: "ACTIVE", revision: "1", created_at: "2026-10-23T00:00:00Z", updated_at: "2026-10-23T00:00:00Z" };
  vi.stubGlobal("fetch", vi.fn(async (input: RequestInfo | URL) => {
    const p = new URL(String(input)).pathname;
    if (p.endsWith(`/projects/${pid}`)) return json({ id: pid, title: "polling project", project_type: "GENERAL", revision: "1", state_revision: "1", archived_at: null });
    if (p.endsWith(`/projects/${pid}/state`)) return json({ project_id: pid, revision: "1", phase_key: "GENERAL", next_action_task_id: null, selected_artifact_version_refs: [], completed_highlight_refs: [] });
    if (p.endsWith("/assist-sessions")) return json({ items: [session] });
    if (p.endsWith(`/assist-sessions/${sid}`)) return json(session);
    if (p.endsWith("/model-selection")) return json({ model: null, revision: "0" });
    if (p.endsWith(`/assist-sessions/${sid}/messages`)) {
      requests++;
      if (slow) await new Promise(resolve => setTimeout(resolve, 3000));
      completedReads++;
      return json({ items: [{ id: mid, session_id: sid, seq: "1", role: "ASSISTANT", status: serverDone ? "COMPLETED" : "RUNNING", intent: "DISCUSS", content: serverDone ? "FINAL_COMPLETED_RESPONSE_PROBE" : "INITIAL_RUNNING_RESPONSE_PROBE", error_code: null, sources: [], usage: { input_tokens: null, output_tokens: null }, cancel_requested: false, steer_requested: false, attachments: [] }] });
    }
    if (p.endsWith("/tool-calls")) return json({ session_id: sid, message_id: mid, message_status: serverDone ? "COMPLETED" : "RUNNING", rounds: [] });
    if (p.endsWith("/model-port")) return json({ provider: "fake", configured: false, model: null, base_url: null, max_call_tokens: null });
    if (p.endsWith("/model-port/verification")) return json({ current_config_fingerprint: null, last: null, matches_current_config: false, worker_startup_validation: "NOT_CONFIGURED" });
    if (p.endsWith("/default-working-directory")) return json({ resource_id: null, canonical_root: null, display_name: null, write_tier: null, default_write_tier: null, status: "UNSET", reason: null, revision: "0" });
    if (p.endsWith("/memory-settings")) return json({ workspace_id: wid, revision: "0", recall_enabled: true, automatic_compaction: true, auto_capture: true });
    if (p.endsWith("/projects") || p.endsWith("/tasks")) return json({ items: [], next_cursor: null });
    return json({ items: [], next_cursor: null });
  }));
  activateRelayConnection({ baseUrl: "http://127.0.0.1:8787", workspaceId: wid, bearerToken: "test-token" });
  const element = () => createElement(MemoryRouter, { initialEntries: [`/projects/${pid}?skill=assist`] }, createElement(AssistView, { targetKind: "PROJECT", targetId: pid }));
  const mounted = await mountReact(element()); unmount = mounted.unmount;
  await act(async () => { await vi.advanceTimersByTimeAsync(500); });
  expect(mounted.wrapper.text()).toContain("INITIAL_RUNNING_RESPONSE_PROBE");
  const initialReads = completedReads;
  slow = true; serverDone = true;
  await act(async () => { await vi.advanceTimersByTimeAsync(10000); });
  const finalVisible = mounted.wrapper.text().includes("FINAL_COMPLETED_RESPONSE_PROBE");
  const oldStillVisible = mounted.wrapper.text().includes("INITIAL_RUNNING_RESPONSE_PROBE");
  const slowCompletedReads = completedReads - initialReads;
  const slowRequests = requests - initialReads;
  mounted.unmount(); unmount = null;
  slow = false;
  const healthy = await mountReact(element()); unmount = healthy.unmount;
  await act(async () => { await vi.advanceTimersByTimeAsync(50); });
  const finalVisibleAfterRemount = healthy.wrapper.text().includes("FINAL_COMPLETED_RESPONSE_PROBE");
  console.log("TRIAGE_ASSIST_MESSAGES_SLOW_POLL", JSON.stringify({ slowRequests, slowCompletedReads, finalVisible, oldStillVisible, finalVisibleAfterRemount }));
  expect(slowCompletedReads).toBeGreaterThanOrEqual(4);
  expect(finalVisibleAfterRemount).toBe(true);
  expect(finalVisible, "completed backend replies must eventually replace the old RUNNING snapshot even when reads are slower than poll interval").toBe(true);
});
