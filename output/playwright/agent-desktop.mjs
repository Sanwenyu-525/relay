import {writeFileSync} from 'node:fs';
import {chromium,expect} from '../../apps/workbench/node_modules/@playwright/test/index.mjs';
const browser=await chromium.connectOverCDP('http://127.0.0.1:19329');
const page=browser.contexts().flatMap(c=>c.pages()).find(p=>p.url().startsWith('http://127.0.0.1:5173'));
if(!page)throw new Error('Expected dev WebView2');
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.locator('nav[aria-label="主导航"] a[href="/projects"]').click();
await page.getByTestId('project-create-open').click();
await page.locator('input[name="project-title"]').fill('Agent 聊天 WebView2 隔离验收');
await page.locator('input[name="project-type"][value="GENERAL"]').check({force:true});
await page.getByTestId('project-create-submit').click();
await expect(page).toHaveURL(/\/projects\/[0-9a-f-]{36}\/tasks$/);
const projectId=/\/projects\/([0-9a-f-]{36})/.exec(page.url())[1];
await page.getByRole('link',{name:'Agent 聊天',exact:true}).click();
await page.getByTestId('agent-new').click();
await page.getByTestId('agent-target-id').selectOption(projectId);
await page.getByTestId('agent-open-target').click();
await page.getByTestId('assist-new-session').click();
await page.getByTestId('assist-draft').fill('请简短说明这个项目可以怎样开始。');
await page.getByTestId('assist-send').click();
await expect(page.locator('.assist-message-list')).toContainText('COMPLETED',{timeout:30000});
await expect(page.locator('.assist-message-list')).not.toContainText('PENDING',{timeout:30000});
const messages=await page.locator('.assist-message-list').innerText();
await page.screenshot({path:'output/playwright/agent-audit/desktop-functional.png'});
const result={projectId,engine:'Windows WebView2 dev + isolated PostgreSQL + Mock Worker',messages,errors};
writeFileSync('output/playwright/agent-audit/desktop-functional.json',JSON.stringify(result,null,2));
console.log(JSON.stringify(result));await browser.close();
